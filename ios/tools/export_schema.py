#!/usr/bin/env python3
"""Generate the iPhone app's database schema and default data from the desktop core.

The iPhone app uses exactly the same SQLite schema (v4) as the Mac / Windows app, so a desktop
backup opens on the phone and the same SQL constraints and triggers protect posted money.
This script runs the desktop migrations on an empty database and writes them out as Swift:

  python3 ios/tools/export_schema.py            # rewrite Schema.generated.swift
  python3 ios/tools/export_schema.py --check    # fail if the Swift file is out of date (CI)
"""
import json
import sqlite3
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "core"))

from server import db  # noqa: E402

OUT = ROOT / "ios" / "AirZeloKit" / "Sources" / "AirZeloKit" / "Database" / "Schema.generated.swift"


def schema_statements():
    with tempfile.TemporaryDirectory() as tmp:
        conn = db.connect(Path(tmp) / "agency.db")
        real_seed = db.seed
        db.seed = lambda c: None  # migrations only: their own data rows are exported below, the seed separately
        try:
            db.migrate(conn)
        finally:
            db.seed = real_seed
        data = []
        for (t,) in conn.execute("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT IN ('schema_migrations') ORDER BY rowid"):
            for r in conn.execute('SELECT * FROM "%s" ORDER BY rowid' % t):
                data.append((t, list(r.keys()), list(r)))
        rows = conn.execute("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' "
                            "ORDER BY rowid").fetchall()
        order = {"table": 0, "index": 1, "trigger": 2}
        stmts = [r["sql"] for r in sorted(rows, key=lambda r: order[r["type"]])]
        versions = [(r["version"], r["name"]) for r in conn.execute("SELECT version, name FROM schema_migrations ORDER BY version")]
        conn.close()
    return stmts, versions, data


def swift_string(s):
    # raw multi-line string literal; the schema never contains the delimiter
    assert '"""#' not in s
    return '#"""\n' + s + '\n"""#'


def render():
    stmts, versions, data = schema_statements()
    seed = {
        "settings": list(db.DEFAULT_SETTINGS.items()),  # ordered pairs: seeding order = desktop row order
        "currencies": db.DEFAULT_CURRENCIES,
        "expense_categories": db.DEFAULT_EXPENSE_CATEGORIES,
        "tax_profiles": db.DEFAULT_TAX_PROFILES,
    }
    out = ["// GENERATED by ios/tools/export_schema.py from core/server/db.py. Do not edit by hand.",
           "// The iPhone app and the desktop app share this schema, so backups move between them.",
           "",
           "enum GeneratedSchema {",
           "    static let version = %d" % versions[-1][0],
           "    static let migrations: [(Int, String)] = [%s]" % ", ".join("(%d, %s)" % (v, json.dumps(n)) for v, n in versions),
           "    static let statements: [String] = ["]
    for s in stmts:
        out.append("        " + swift_string(s).replace("\n", "\n        ") + ",")
    out.append("    ]")
    out.append("    /// Rows the migrations themselves insert (e.g. the 'Loan interest' expense category of v4), applied before the seed.")
    out.append("    static let migrationDataJSON = %s" % swift_string(json.dumps(data, ensure_ascii=False)))
    out.append("    static let seedJSON = %s" % swift_string(json.dumps(seed, ensure_ascii=False, indent=1)))
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("Schema.generated.swift is out of date: run python3 ios/tools/export_schema.py")
            sys.exit(1)
        print("Schema.generated.swift matches the desktop schema")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
